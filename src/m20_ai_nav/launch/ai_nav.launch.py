"""Bring up the learned navigator in one of three modes (docs/AI_NAV_BRIEF.md §4.1).

  ros2 launch m20_ai_nav ai_nav.launch.py mode:=follow_path params_file:=<nav2_params.yaml>
  ros2 launch m20_ai_nav ai_nav.launch.py mode:=standalone  params_file:=<nav2_params.yaml>
  ros2 launch m20_ai_nav ai_nav.launch.py mode:=direct      params_file:=<nav2_params.yaml>

follow_path : Nav2 WITHOUT controller_server (planner, behaviors, BT navigator,
              waypoint follower, velocity smoother, plus a standalone local costmap
              so the behaviors and the BT's clear-costmap services keep working) +
              our node serving /follow_path. REPLACES nav2_bringup navigation_launch.py.
standalone  : velocity smoother + our node serving /navigate_to_pose (A* on /map).
direct      : velocity smoother + our node serving /navigate_to_pose (no map).

All modes: our node -> /cmd_vel_nav -> velocity_smoother -> /cmd_vel -> bridge, the
same chain Nav2 uses, so the commander veto and bridge watchdog are unchanged.
"""
import os

from launch import LaunchDescription
import sys

from launch.actions import DeclareLaunchArgument, ExecuteProcess, OpaqueFunction
from launch.substitutions import LaunchConfiguration
from launch_ros.actions import Node


STAGED_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))


def _installed():
    try:
        from ament_index_python.packages import get_package_share_directory
        return get_package_share_directory("m20_ai_nav")
    except Exception:  # noqa: BLE001 — not colcon-installed: running from a staged tree
        return None


def _default_model():
    share = _installed()
    return os.path.join(share or STAGED_ROOT, "models", "m20_nav_policy.onnx")


SITE_PARAMS = {
    # outdoor pad: circular clearance (the pivot sweep is 0.53 m)
    "outdoor": {"planner_robot_radius": 0.55},
    # office: plan through doors on the half-width (0.265 + 0.05); the NavCore pivot
    # guard stops turn-in-place whenever anything is inside the 0.53 m sweep
    "office": {"planner_robot_radius": 0.32, "planner_pivot_clear": 0.6,
               "lookahead": 0.9, "stuck_timeout_s": 20.0},
}


def _controller(mode, model, frame, site="outdoor"):
    params = {"mode": mode, "model_path": model, "global_frame": frame, **SITE_PARAMS[site]}
    if _installed():
        return Node(package="m20_ai_nav", executable="ai_controller", name="m20_ai_controller",
                    output="screen", parameters=[params])
    # staged source tree (tools/nav/bringup_plan_a.sh docker-cp's src/m20_ai_nav to /cfg)
    args = [sys.executable, "-m", "m20_ai_nav.controller_node", "--ros-args",
            "-r", "__node:=m20_ai_controller"]
    for k, v in params.items():
        args += ["-p", f"{k}:={v}"]
    env = dict(os.environ)
    env["PYTHONPATH"] = STAGED_ROOT + os.pathsep + env.get("PYTHONPATH", "")
    return ExecuteProcess(cmd=args, output="screen", additional_env={"PYTHONPATH": env["PYTHONPATH"]})


LOCAL_CLEAR_STOCK = "local_costmap/clear_entirely_local_costmap"
LOCAL_CLEAR_OURS = "costmap/clear_entirely_costmap"


def _derived_bt(stock_name):
    """Nav2's stock BT with ONLY the local-costmap clear service renamed (the
    standalone costmap's fixed node name is costmap/costmap). Generated from the
    INSTALLED Nav2 so it tracks the distro; written to a temp file."""
    import tempfile
    from ament_index_python.packages import get_package_share_directory
    src = os.path.join(get_package_share_directory("nav2_bt_navigator"), "behavior_trees", stock_name)
    xml = open(src).read()
    if LOCAL_CLEAR_STOCK not in xml:
        raise RuntimeError(f"{src}: expected service {LOCAL_CLEAR_STOCK} not found — Nav2 BT changed")
    fd, path = tempfile.mkstemp(prefix="m20_ai_" + stock_name.replace(".xml", "_"), suffix=".xml")
    with os.fdopen(fd, "w") as f:
        f.write("<!-- GENERATED by m20_ai_nav ai_nav.launch.py from " + src + " -->\n"
                + xml.replace(LOCAL_CLEAR_STOCK, LOCAL_CLEAR_OURS))
    return path


def _follow_path_params(params):
    """Derive the follow_path-mode params from the stack's nav2_params.yaml, which
    stays single-source: copy local_costmap -> costmap.costmap, point the
    behaviors at that costmap's topics, and give bt_navigator our BT (local clear
    service renamed). Written to a temp file; nav2_params.yaml is not modified."""
    import tempfile
    import yaml
    with open(params) as f:
        p = yaml.safe_load(f)
    lc = p.get("local_costmap", {}).get("local_costmap")
    if lc is None:
        raise RuntimeError(f"{params}: no local_costmap.local_costmap block")
    import copy
    p["costmap"] = {"costmap": copy.deepcopy(lc)}   # NOT a shared ref: see dumper below
    bs = p.setdefault("behavior_server", {}).setdefault("ros__parameters", {})
    bs["costmap_topic"] = "costmap/costmap_raw"
    bs["footprint_topic"] = "costmap/published_footprint"
    bt = p.setdefault("bt_navigator", {}).setdefault("ros__parameters", {})
    # BT action/service clients wait 1 s for their servers by default; our Python
    # controller + 9 Nav2 processes on one box need longer for DDS discovery
    # (measured: /follow_path up 1.4 s before activation, still "not available")
    bt["wait_for_service_timeout"] = 10000
    # BT action nodes give the server default_server_timeout (20 ms!) to ACK each
    # goal; a Python server on a loaded CPU misses that (measured: office smoke with
    # training running -> "Timed out ... acknowledge goal request for follow_path",
    # every 1 Hz replan). The robot computer will be loaded too.
    bt["default_server_timeout"] = 1000
    bt["default_nav_to_pose_bt_xml"] = _derived_bt("navigate_to_pose_w_replanning_and_recovery.xml")
    bt["default_nav_through_poses_bt_xml"] = _derived_bt(
        "navigate_through_poses_w_replanning_and_recovery.xml")
    fd, path = tempfile.mkstemp(prefix="m20_ai_nav_follow_path_", suffix=".yaml")
    class NoAlias(yaml.SafeDumper):
        # rcl's param parser rejects YAML anchors/aliases ("Will not support
        # aliasing") and kills every Nav2 node at startup — never emit them
        def ignore_aliases(self, data):
            return True
    with os.fdopen(fd, "w") as f:
        yaml.dump(p, f, Dumper=NoAlias)
    return path


def _cm_params():
    try:
        from ament_index_python.packages import get_package_share_directory
        p = os.path.join(get_package_share_directory("m20_navigation"), "config", "collision_monitor.yaml")
        if os.path.exists(p):
            return p
    except Exception:  # noqa: BLE001
        pass
    p = os.path.join(STAGED_ROOT, "..", "m20_navigation", "config", "collision_monitor.yaml")
    if not os.path.exists(p):
        raise RuntimeError("collision_monitor.yaml not found (m20_navigation/config)")
    return p


def _bt_timeouts(params):
    """bt_navigator with the same server-timeout fixes as follow_path mode."""
    import tempfile
    import yaml
    with open(params) as f:
        p = yaml.safe_load(f)
    bt = p.setdefault("bt_navigator", {}).setdefault("ros__parameters", {})
    bt["wait_for_service_timeout"] = 10000
    bt["default_server_timeout"] = 1000
    fd, path = tempfile.mkstemp(prefix="m20_bt_", suffix=".yaml")
    with os.fdopen(fd, "w") as f:
        yaml.safe_dump(p, f)
    return path


def _setup(context):
    mode = LaunchConfiguration("mode").perform(context)
    site = LaunchConfiguration("site").perform(context)
    params = LaunchConfiguration("params_file").perform(context)
    model = LaunchConfiguration("model_path").perform(context) or _default_model()
    frame = LaunchConfiguration("global_frame").perform(context)
    if site not in SITE_PARAMS:
        raise RuntimeError(f"site must be one of {sorted(SITE_PARAMS)}, got {site!r}")
    if mode not in ("nav2", "follow_path", "standalone", "direct"):
        raise RuntimeError(f"mode must be nav2|follow_path|standalone|direct, got {mode!r}")
    if site == "office" and mode == "direct":
        # direct = no map, straight-line carrot: it cannot route through doors and
        # walks into walls trying (office smoke 2026-11-04). Refuse, don't degrade.
        raise RuntimeError("mode:=direct is not allowed with site:=office (no map -> cannot "
                           "route through doors); use follow_path or standalone")
    if not os.path.exists(params):
        raise RuntimeError(f"params_file not found: {params}")
    if mode != "nav2" and not os.path.exists(model):
        raise RuntimeError(f"policy model not found: {model}")
    cm = LaunchConfiguration("collision_monitor").perform(context).lower() in ("1", "true", "yes")
    smoothed = "cmd_vel_smoothed" if cm else "cmd_vel"
    out = [
        Node(package="nav2_velocity_smoother", executable="velocity_smoother",
             name="velocity_smoother", output="screen", parameters=[params],
             remappings=[("cmd_vel", "cmd_vel_nav"), ("cmd_vel_smoothed", smoothed)]),
    ]
    if mode != "nav2":
        out.insert(0, _controller(mode, model, frame, site))
    managed = ["velocity_smoother"]
    if cm:
        # last safety layer for EVERY mode: cmd_vel_smoothed -> collision_monitor -> cmd_vel
        out.append(Node(package="nav2_collision_monitor", executable="collision_monitor",
                        name="collision_monitor", output="screen",
                        parameters=[_cm_params()]))
        managed.append("collision_monitor")
    if mode == "nav2":
        # CLASSICAL Nav2 (controller_server from params_file: DWB / RPP / MPPI variants),
        # launched here instead of nav2_bringup so the collision monitor can sit in the
        # chain (Humble's navigation_launch.py has no slot for it)
        out += [
            Node(package="nav2_controller", executable="controller_server", output="screen",
                 parameters=[params], remappings=[("cmd_vel", "cmd_vel_nav")]),
            Node(package="nav2_planner", executable="planner_server", name="planner_server",
                 output="screen", parameters=[params]),
            Node(package="nav2_behaviors", executable="behavior_server", name="behavior_server",
                 output="screen", parameters=[params]),
            Node(package="nav2_bt_navigator", executable="bt_navigator", name="bt_navigator",
                 output="screen", parameters=[_bt_timeouts(params)]),
            Node(package="nav2_waypoint_follower", executable="waypoint_follower",
                 name="waypoint_follower", output="screen", parameters=[params]),
        ]
        managed = ["controller_server", "planner_server", "behavior_server", "bt_navigator",
                   "waypoint_follower"] + managed
    if mode == "follow_path":
        fp_params = _follow_path_params(params)
        out += [
            # local costmap without controller_server. Humble's standalone executable
            # names its node costmap/costmap regardless of launch name/namespace, so
            # it reads the local_costmap block re-keyed under costmap.costmap.
            Node(package="nav2_costmap_2d", executable="nav2_costmap_2d", output="screen",
                 parameters=[fp_params]),
            Node(package="nav2_planner", executable="planner_server", name="planner_server",
                 output="screen", parameters=[fp_params]),
            Node(package="nav2_behaviors", executable="behavior_server",
                 name="behavior_server", output="screen", parameters=[fp_params]),
            Node(package="nav2_bt_navigator", executable="bt_navigator", name="bt_navigator",
                 output="screen", parameters=[fp_params]),
            Node(package="nav2_waypoint_follower", executable="waypoint_follower",
                 name="waypoint_follower", output="screen", parameters=[fp_params]),
        ]
        # Costmap2DROS run standalone never creates a lifecycle bond (inside
        # controller_server the parent owns that), so a bonded manager aborts
        # bringup after 4 s. It gets its own manager with bonds off (verified).
        out.append(Node(package="nav2_lifecycle_manager", executable="lifecycle_manager",
                        name="lifecycle_manager_ai_costmap", output="screen",
                        parameters=[{"autostart": True, "bond_timeout": 0.0,
                                     "node_names": ["costmap/costmap"]}]))
        managed = ["planner_server", "behavior_server",
                   "bt_navigator", "waypoint_follower", "velocity_smoother"]
    out.append(Node(package="nav2_lifecycle_manager", executable="lifecycle_manager",
                    name="lifecycle_manager_ai_nav", output="screen",
                    parameters=[{"autostart": True, "node_names": managed}]))
    return out


def generate_launch_description():
    return LaunchDescription([
        DeclareLaunchArgument("mode", default_value="follow_path"),
        DeclareLaunchArgument("params_file"),
        DeclareLaunchArgument("model_path", default_value=""),
        DeclareLaunchArgument("global_frame", default_value="map"),
        DeclareLaunchArgument("collision_monitor", default_value="false",
                              description="true = Nav2 collision_monitor after the smoother (office: on)"),
        DeclareLaunchArgument("site", default_value="outdoor",
                              description="outdoor | office (pass the office-overlaid params_file too)"),
        OpaqueFunction(function=_setup),
    ])
