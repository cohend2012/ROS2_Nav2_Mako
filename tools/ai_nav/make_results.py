#!/usr/bin/env python3
"""Compose docs/ai_nav/RESULTS.md from the gate JSON files (never hand-edit numbers).

    python3 tools/ai_nav/make_results.py
Inputs (any missing one is reported as NOT RUN, never silently skipped):
  docs/ai_nav/eval_v1.json, eval_baseline.json, g4_offline.json, smoke.json,
  mission_g5/report_*.json, src/m20_ai_nav/models/m20_nav_policy.onnx.json,
  <train_log> (optional --train-log)
"""
import argparse
import glob
import json
import os

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
D = os.path.join(REPO, "docs", "ai_nav")


def load(name):
    p = os.path.join(D, name)
    return json.load(open(p)) if os.path.exists(p) else None


def pct(x):
    return f"{100 * x:.1f}%"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--train-log", default=None)
    a = ap.parse_args()
    L = ["# M20-Brain gate results", "",
         "GENERATED by `tools/ai_nav/make_results.py` from the JSON files in this folder.",
         "Do not edit numbers by hand. Bars are in docs/AI_NAV_BRIEF.md §5.", ""]
    meta = json.load(open(os.path.join(REPO, "src", "m20_ai_nav", "models", "m20_nav_policy.onnx.json")))
    L += ["## Shipped policy", "",
          f"- `src/m20_ai_nav/models/m20_nav_policy.onnx`: {meta['timesteps']:,} PPO steps, "
          f"OBS_VERSION {meta['obs_version']}, ONNX-vs-PyTorch parity {meta['parity_max_abs_err']:.1e}, "
          f"sha256 `{meta['sha256'][:16]}…`", ""]
    if a.train_log and os.path.exists(a.train_log):
        rows = [json.loads(x) for x in open(a.train_log)]
        L += ["Training curve (rolling last 200 episodes per checkpoint):", "",
              "| steps | obstacle density | success | collision | tipped | wall |", "|---|---|---|---|---|---|"]
        for r in rows[::3] + ([rows[-1]] if (len(rows) - 1) % 3 else []):
            L.append(f"| {r['t']:,} | {r['density']} | {pct(r['success'])} | {pct(r['collision'])} | "
                     f"{pct(r['tipped'])} | {r['wall_s'] // 60} min |")
        L.append("")
    ev, bl = load("eval_v1.json"), load("eval_baseline.json")
    L += ["## G1: held-out procedural episodes (full density, domain randomization on)", ""]
    if ev:
        L += ["| policy | n | success | collision | tipped | timeout | SPL | G1 bar |", "|---|---|---|---|---|---|---|---|"]
        for name, e in (("**learned (PPO)**", ev), ("scripted baseline", bl)):
            if e is None:
                L.append(f"| {name} | NOT RUN | | | | | | |"); continue
            g = e["G1"]
            L.append(f"| {name} | {g['n']} | {pct(g['success'])} | {pct(g['collision'])} | {pct(g['tipped'])} | "
                     f"{pct(g['timeout'])} | {g['spl']:.3f} | {'PASS' if g['pass'] else 'FAIL'} |")
        L += ["", "SPL uses the straight-line distance as the shortest path, so it is conservative around obstacles.", "",
              "## G2: gap-width sweep (barrier with one gap, goal behind it)", "",
              "| gap (m) | learned success | learned collision | baseline success | baseline collision |", "|---|---|---|---|---|"]
        for w, g in ev["G2"].items():
            b = (bl or {}).get("G2", {}).get(w)
            L.append(f"| {w} | {pct(g['success'])} | {pct(g['collision'])} | "
                     + (f"{pct(b['success'])} | {pct(b['collision'])} |" if b else "— | — |"))
        L += ["", "## Field scene as deployed (`oil_gas_field.xml`; standalone mode: A* path + NavCore + policy)", "",
              "| policy | n | success | collision | tipped | timeout | SPL |", "|---|---|---|---|---|---|---|"]
        for name, e in (("learned", ev), ("baseline", bl)):
            if e:
                f = e["field"]
                L.append(f"| {name} | {f['n']} | {pct(f['success'])} | {pct(f['collision'])} | {pct(f['tipped'])} | "
                         f"{pct(f['timeout'])} | {f['spl']:.3f} |")
        L.append("")
    else:
        L += ["NOT RUN", ""]
    sm = load("smoke.json")
    L += ["## ROS 2 wiring smoke (real Humble + Nav2, kinematic fake world)", ""]
    if sm:
        L += ["| mode | nav goal (around skid1) | final error | agent: read PG-101 (true 64) + return home | verdict |",
              "|---|---|---|---|---|"]
        for m, r in sm["modes"].items():
            n, ag = r["nav"], r["agent"]
            L.append(f"| `{m}` | status {n.get('status')} in {n.get('duration_s')} s | {n.get('final_err_m')} m | "
                     f"read {ag.get('reading')}, home err {ag.get('home_err_m')} m | "
                     f"{'PASS' if n['pass'] and ag['pass'] else 'FAIL'} |")
        L += ["", f"Environment: {sm['env']}", ""]
    else:
        L += ["NOT RUN", ""]
    g4 = load("g4_offline.json")
    L += ["## G4: language → grounded mission (10 prompts)", ""]
    for name in ("g4_offline.json", "g4_claude.json", "g4_cosmos.json"):
        g = load(name)
        tag = name[3:-5]
        L.append(f"- `{tag}`: " + (f"**{g['passed']}/{g['of']}** {'PASS' if g['pass'] else 'FAIL'}" if g else
                                    "NOT RUN here (needs credentials / endpoint)"))
    if g4:
        L += ["", "| prompt | offline plan | ok |", "|---|---|---|"]
        for r in g4["rows"]:
            L.append(f"| {r['prompt']} | {' → '.join(r['plan'])} | {'✓' if r['pass'] else '✗ ' + '; '.join(r['errors'])} |")
    L.append("")
    reps = sorted(glob.glob(os.path.join(D, "mission_g5", "report_*.json")))
    L += ["## G5: end-to-end gauge mission in MuJoCo", "",
          '"read all the gauges and return to where you started", offline backend, standalone-mode '
          "planning (A*) + learned policy on the vendor M20 physics, first-person camera.", ""]
    if reps:
        r = json.load(open(reps[-1]))
        g5, sim = r.get("G5", {}), r.get("sim", {})
        L += [f"- mission success: **{r['success']}** ({r['detail']}); sim time {sim.get('sim_time_s')} s; "
              f"collisions {sim.get('collisions')}; home error **{sim.get('home_error_m')} m**",
              f"- gauges within 5% FS: **{g5.get('within')}/{g5.get('of')}**, confident-but-wrong: "
              f"**{g5.get('confident_wrong')}** → G5 **{'PASS' if g5.get('pass') else 'FAIL'}**", "",
              "| gauge | true | read | error (% FS) | status |", "|---|---|---|---|---|"]
        for row in g5.get("rows", []):
            L.append(f"| {row['gauge']} | {row['true']} | {row.get('read')} | {row.get('err_pct_fs', '—')} | {row['status']} |")
        L.append("")
    else:
        L += ["NOT RUN", ""]
    if ev and bl:
        g, b, f, fb = ev["G1"], bl["G1"], ev["field"], bl["field"]
        L += ["## What the numbers say (read this before deploying)", "",
              f"- **The learned policy is strongest in dense, unstructured clutter.** G1 success "
              f"{pct(g['success'])} vs {pct(b['success'])} for the scripted baseline; most baseline "
              f"failures are timeouts ({pct(b['timeout'])}), where it boxes itself in.",
              f"- **It is not yet safer.** Collisions {pct(g['collision'])} vs {pct(b['collision'])}, "
              f"plus {pct(g['tipped'])} tip-overs that the baseline never has.",
              f"- **On the real site layout with a global path, the scripted baseline wins**: "
              f"{pct(fb['success'])} vs {pct(f['success'])} ({int(round(f['collision'] * f['n']))} collisions, "
              f"{int(round(f['tipped'] * f['n']))} tip-over in {f['n']}). When A* already gives a good path through an open "
              "pad, a simple reactive tracker is enough; the learned policy has no edge there yet.",
              "- **G2 cannot separate them.** Both pass every gap width down to 1.0 m, so the brief's \"strictly "
              "better on gaps < 1.2 m\" bar is not demonstrated. The sweep needs narrower gaps or a dynamic obstacle.",
              "- **Recommendation:** run G3 with `follow_path` against DWB on the owner box before relying on it. "
              "Next training run: (1) add the site's long ground pipes to the procedural slots, (2) add a "
              "tip-over/roll-rate penalty, (3) curriculum on near-contact pivots. The policy contract (spec.py) does "
              "not change, so the ROS side needs no edits to ship v2.", ""]
    # ---------------- office ----------------
    ov2, ov1, obl = load("office_v2.json"), load("office_v1.json"), load("office_baseline.json")
    if ov2 or ov1:
        L += ["## Office gates (procedural offices, A* + NavCore + shield as deployed)", "",
              "O1 = held-out offices (people 0-3), O2 = door-width sweep (no people), O3 = 3 walking people.", "",
              "| policy | O1 success | O1 collision | O1 timeout/stuck | O3 success | O3 collision |",
              "|---|---|---|---|---|---|"]
        for name, e in (("**office v2 (shielded RL)**", ov2), ("v1 (outdoor-trained)", ov1), ("scripted baseline", obl)):
            if e and "O1" in e:
                o1, o3 = e["O1"], e["O3"]
                L.append(f"| {name} | {pct(o1['success'])} | {pct(o1['collision'])} | {pct(o1['timeout'])} | "
                         f"{pct(o3['success'])} | {pct(o3['collision'])} |")
        L += ["", "| door width | " + " | ".join(n for n, e in (("v2", ov2), ("v1", ov1), ("baseline", obl)) if e) + " |",
              "|---|" + "---|" * sum(1 for e in (ov2, ov1, obl) if e)]
        for w in ("0.80", "0.85", "0.90", "1.00"):
            cells = [f"{pct(e['O2'][w]['success'])} ok / {pct(e['O2'][w]['collision'])} coll"
                     for e in (ov2, ov1, obl) if e and "O2" in e]
            L.append(f"| {w} m | " + " | ".join(cells) + " |")
        L.append("")
    so = load("smoke_office.json")
    if so:
        L += ["### Office ROS 2 wiring (real Humble + Nav2, office overlay, box-exact LiDAR)", "",
              "Reception → meeting room through its **0.85 m door**, then \"go to the meeting room and come back\".", "",
              "| mode | nav goal | agent mission | verdict |", "|---|---|---|---|"]
        for m, r in so["modes"].items():
            n, ag = r["nav"], r["agent"]
            L.append(f"| `{m}` | {('status ' + str(n.get('status')) + ', err ' + str(n.get('final_err_m')) + ' m') if 'status' in n else n.get('why')} | "
                     f"{ag.get('detail', ag.get('why'))} | {'PASS' if n['pass'] and ag['pass'] else 'FAIL'} |")
        L += ["", "`direct` is refused indoors by design (no map → cannot route through doors).", ""]
    reps = sorted(glob.glob(os.path.join(D, "mission_office", "report_*.json")))
    if reps:
        L += ["### Office missions in MuJoCo (office demo site, vendor M20 physics)", "",
              "| request | plan | result | sim time | home error |", "|---|---|---|---|---|"]
        for p_ in reps:
            r = json.load(open(p_)); sim = r.get("sim", {})
            L.append(f"| {r['request']} | {' → '.join(x['action'] + ':' + x.get('target', '') for x in r.get('plan', []))} | "
                     f"{'✓' if r['success'] else '✗ ' + r['detail']} | {sim.get('sim_time_s')} s | {sim.get('home_error_m')} m |")
        L.append("")
    L += ["## Not measured here (owner box)", "",
          "- **G3**: the full MuJoCo + ROS stack batch with `M20_AI_CONTROLLER=follow_path`. It needs the "
          "m20_autonomy/m20_sim images and the drdds bridge, which are not buildable in this cloud "
          "session (packages.ros.org is blocked by its network policy).",
          "- G4 with real VLMs (Claude: `ANTHROPIC_API_KEY`; Cosmos: a GPU endpoint).", ""]
    out = os.path.join(D, "RESULTS.md")
    open(out, "w").write("\n".join(L))
    print("wrote", out)


if __name__ == "__main__":
    main()
