#!/usr/bin/env python3
"""Generate the fixed OFFICE demo site: office.xml (next to M20.xml) + its landmark file.

    python3 tools/sim/make_office_scene.py [--seed 7] [--out-dir <dir with M20.xml>]

Writes:
  <out-dir>/office.xml                        scene (includes M20.xml; 2 walking people)
  tools/sim/office.xml                        same, committed
  src/m20_agent/config/office_landmarks.yaml  named rooms + routines for the agent
The layout comes from the SAME generator the policy trains on (m20_ai_nav.sim.office),
with a fixed seed and real room names. Approach poses are picked from the planner's
free space (>= 0.6 m clearance), so every named place is reachable for the M20.
"""
import argparse
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(REPO, "src", "m20_ai_nav"))

import mujoco  # noqa: E402
import numpy as np  # noqa: E402
import yaml  # noqa: E402

from m20_ai_nav.grid_planner import GridPlanner  # noqa: E402
from m20_ai_nav.sim import office  # noqa: E402
from m20_ai_nav.sim.raster import rasterize  # noqa: E402

DEFAULT_DIR = os.path.expanduser(
    "~/m20_sim/sdk_deploy/src/M20_sdk_deploy/M20_description/m20_mjcf/mjcf")
ROOMS = ["kitchen", "meeting_room", "open_office", "server_room", "manager_office", "print_room"]
ALIASES = {
    "kitchen": ["the kitchen", "break room", "coffee", "coffee machine"],
    "meeting_room": ["meeting room", "conference room", "boardroom"],
    "open_office": ["open office", "desks", "the office"],
    "server_room": ["server room", "IT room", "network closet"],
    "manager_office": ["manager's office", "manager office", "the boss's office"],
    "print_room": ["printer", "print room", "copier"],
}


def to_xml(L):
    lines = ['<!-- GENERATED by tools/sim/make_office_scene.py — do not edit by hand. -->',
             '<mujoco model="m20_office">', '  <include file="M20.xml"/>', '  <worldbody>']
    for i, b in enumerate(L.boxes):
        q = (math.cos(b.yaw / 2), 0, 0, math.sin(b.yaw / 2))
        rgba = {"desk": "0.55 0.4 0.25 1", "chair": "0.2 0.2 0.25 1",
                "cabinet": "0.5 0.5 0.55 1"}.get(b.kind, "0.85 0.85 0.82 1")
        lines.append(f'    <geom name="{b.kind}_{i}" type="box" size="{b.hx:.3f} {b.hy:.3f} {b.hz:.3f}" '
                     f'pos="{b.x:.3f} {b.y:.3f} {b.hz:.3f}" quat="{q[0]:.5f} 0 0 {q[3]:.5f}" rgba="{rgba}"/>')
    for k, p in enumerate(L.people):
        x, y = office.person_xy(p, 0.0)
        lines.append(f'    <body name="person{k}" mocap="true" pos="{x:.3f} {y:.3f} 0.85">'
                     f'<geom name="person{k}_geom" type="cylinder" size="0.25 0.85" rgba="0.2 0.45 0.8 1"/></body>')
    lines += ['  </worldbody>', '</mujoco>', '']
    return "\n".join(lines)


def free_point_near(pl, x, y, clear=0.6, max_r=3.0):
    r0, c0 = pl.world_to_cell(x, y)
    best = None
    rad = int(max_r / pl.res)
    for dr in range(-rad, rad + 1):
        for dc in range(-rad, rad + 1):
            r, c = r0 + dr, c0 + dc
            if 0 <= r < pl.h and 0 <= c < pl.w and pl.dist[r, c] > clear:
                d = dr * dr + dc * dc
                if best is None or d < best[0]:
                    best = (d, r, c)
    if best is None:
        raise RuntimeError(f"no free point within {max_r} m of ({x:.1f},{y:.1f})")
    return pl.cell_to_world(best[1], best[2])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--out-dir", default=DEFAULT_DIR)
    a = ap.parse_args()
    if not os.path.exists(os.path.join(a.out_dir, "M20.xml")):
        sys.exit(f"{a.out_dir}/M20.xml missing — run tools/setup_sim.sh first")
    rng = np.random.default_rng(a.seed)
    L = office.generate(rng, n_people=2, room_names=ROOMS)
    xml = to_xml(L)
    for d in (a.out_dir, HERE):
        open(os.path.join(d, "office.xml"), "w").write(xml)
    m = mujoco.MjModel.from_xml_path(os.path.join(a.out_dir, "office.xml"))
    dd = mujoco.MjData(m); mujoco.mj_forward(m, dd)
    pl = GridPlanner(robot_radius=0.32, inflation_radius=0.8)
    pl.set_map(*rasterize(m, dd, res=0.10))
    cy, cw = L.corridor
    lms = []
    for room in L.rooms:
        px, py = free_point_near(pl, *room.inside)
        dx, dy = room.door
        yaw = math.atan2(py - dy, px - dx)              # facing into the room
        lms.append({"name": room.name, "type": "room", "aliases": ALIASES.get(room.name, []),
                    "position": [round(room.inside[0], 2), round(room.inside[1], 2)],
                    "approach": [round(px, 2), round(py, 2), round(yaw, 3)]})
        ox, oy = free_point_near(pl, dx, cy, clear=0.6)  # corridor spot outside its door
        lms.append({"name": room.name + "_door", "type": "area",
                    "aliases": [room.name.replace("_", " ") + " door"],
                    "position": [round(dx, 2), round(room.door[1], 2)],
                    "approach": [round(ox, 2), round(oy, 2), round(math.atan2(dy - oy, dx - ox), 3)]})
    rx, ry = free_point_near(pl, -office.HALF + 1.0, cy)
    lms.append({"name": "reception", "type": "area", "aliases": ["front desk", "entrance", "lobby"],
                "position": [round(rx, 2), round(ry, 2)], "approach": [round(rx, 2), round(ry, 2), 0.0]})
    kx, ky = free_point_near(pl, office.HALF - 1.0, cy)
    lms.append({"name": "dock", "type": "dock", "aliases": ["charger", "charging station", "base"],
                "position": [round(kx, 2), round(ky, 2)], "approach": [round(kx, 2), round(ky, 2), math.pi]})
    doc = {
        "frame": "map",
        "_comment": "GENERATED by tools/sim/make_office_scene.py for the sim office "
                    f"(seed {a.seed}). For YOUR office: map it, then teach places by voice "
                    "(\"this is the kitchen\") or copy this file's shape.",
        "landmarks": lms,
        "routines": {
            "office_round": {"aliases": ["the mission", "office round", "rounds", "morning round"],
                             "description": "check every room, end at the dock",
                             "steps": [{"action": "inspect", "target": r.name,
                                        "question": "Is anything out of place: open door, spill, obstruction, person needing help?"}
                                       for r in L.rooms] + [{"action": "goto", "target": "dock"}]},
            "coffee_run": {"aliases": ["coffee run"], "description": "go to the kitchen and come back",
                           "steps": [{"action": "goto", "target": "kitchen"}, {"action": "wait", "seconds": 10},
                                     {"action": "return_home"}]},
        },
        "default_routine": "office_round",
    }
    out = os.path.join(REPO, "src", "m20_agent", "config", "office_landmarks.yaml")
    with open(out, "w") as f:
        yaml.safe_dump(doc, f, sort_keys=False)
    print(f"office: {len(L.boxes)} boxes, {len(L.rooms)} rooms, doors "
          f"{[round(d[2], 2) for d in L.doors]}, corridor {cw:.2f} m -> {out}")


if __name__ == "__main__":
    main()
